// Writes the contract ABIs the SDK uses into packages/sdk/src/abi.ts (run after `forge build`).
import { readFileSync, writeFileSync } from 'fs';
const out = (p) => JSON.parse(readFileSync(new URL(`../out/${p}`, import.meta.url))).abi;
const abis = {
  vaultAbi: out('PrivateVault.sol/PrivateVault.json'),
  feeCollectorAbi: out('FeeCollector.sol/FeeCollector.json'),
  entryPointAbi: out('EntryPoint.sol/EntryPoint.json'),
};
let src = '// Generated by contracts/script/export-abi.mjs — do not edit.\n';
for (const [k, v] of Object.entries(abis)) src += `export const ${k} = ${JSON.stringify(v, null, 2)} as const;\n\n`;
writeFileSync(new URL('../../packages/sdk/src/abi.ts', import.meta.url), src);
console.log('wrote packages/sdk/src/abi.ts');
